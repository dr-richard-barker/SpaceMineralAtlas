"""Stage 9b: turn analysis results into LaTeX macros.

Every number that appears in the manuscript is defined here as a \newcommand
read from the analysis JSON, and the manuscript cites the macro rather than the
value. This is a structural fix, not a stylistic one: in the predecessor project
the reported PCA variance, model accuracies and effect sizes had all drifted away
from what the code computed, because each was typed into the LaTeX by hand. A
number that can only enter the text through this file cannot drift.

If a macro is referenced in the manuscript but not defined here, LaTeX fails with
an undefined control sequence -- which is the desired behaviour.

Run:  python scripts_generate_numbers.py
Output: manuscript/generated_numbers.tex
"""

import json
import logging
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / "src"))

import pandas as pd

from spacemineralatlas.paths import CATALOG, MANUSCRIPT, PROCESSED, RESULTS

logging.basicConfig(level=logging.INFO, format="%(levelname)-7s | %(message)s")
log = logging.getLogger("numbers")

ELEMENT_KEYS = {
    "calcium": "Ca", "potassium": "K", "iron": "Fe", "sodium": "Na",
    "magnesium": "Mg", "zinc": "Zn", "sulfur": "S", "phosphorus": "P",
    "manganese": "Mn", "copper": "Cu", "boron": "B", "aluminium": "Al",
}
CROP_KEYS = {"lettuce": "Let", "tokyo_bekana": "TB"}

# LaTeX macro names cannot contain digits or underscores, so integers are spelled.
DIGIT_WORDS = str.maketrans("0123456789", "ZOTHFVSNEI")


def macro_name(*parts: str) -> str:
    """Build a LaTeX-safe macro name from parts."""
    joined = "".join(p.capitalize() for p in parts if p)
    return joined.replace("_", "").translate(DIGIT_WORDS)


class Macros:
    """Accumulates \newcommand definitions with their source recorded."""

    def __init__(self) -> None:
        self.entries: list[tuple[str, str, str]] = []
        self._seen: set[str] = set()

    def add(self, name: str, value, source: str, *, fmt: str = "{}") -> None:
        if name in self._seen:
            raise ValueError(f"duplicate macro {name!r}")
        self._seen.add(name)
        rendered = fmt.format(value) if value is not None else "n/a"
        self.entries.append((name, rendered, source))

    def render(self) -> str:
        lines = [
            "% generated_numbers.tex -- GENERATED by scripts_generate_numbers.py",
            "% Do not edit. Every value is read from analysis/results/ or catalog/.",
            "% Regenerate with `make numbers` after any change to the analysis.",
            "",
        ]
        width = max(len(n) for n, _, _ in self.entries) + 2
        for name, value, source in self.entries:
            lines.append(f"% {source}")
            lines.append(f"\\newcommand{{\\{name}}}{{{value}}}".ljust(width))
            lines.append("")
        return "\n".join(lines)


def main() -> None:
    plant = json.loads((RESULTS / "plant_summary.json").read_text())
    astro = json.loads((RESULTS / "astronaut_summary.json").read_text())
    ml = json.loads((RESULTS / "ml_results.json").read_text())
    lsda = json.loads((CATALOG / "lsda_catalog_summary.json").read_text())
    supply = json.loads((RESULTS / "supply_summary.json").read_text())
    integration = json.loads((RESULTS / "integration_summary.json").read_text())
    comparison = pd.read_csv(RESULTS / "plant_contrasts_comparison.csv")
    overload = pd.read_csv(RESULTS / "overload_assessment.csv")
    qc = json.loads((RESULTS / "qc_report.json").read_text())

    m = Macros()

    # --- Sample sizes -----------------------------------------------------
    m.add("NSamples", plant["n_samples"], "plant_summary.json:n_samples")
    for crop, n in plant["n_by_crop"].items():
        m.add(macro_name("N", CROP_KEYS[crop]), n, f"plant_summary.json:n_by_crop.{crop}")
    for key, n in plant["n_by_crop_condition"].items():
        crop, condition = key.split("/")
        m.add(macro_name("N", CROP_KEYS[crop], condition), n,
              f"plant_summary.json:n_by_crop_condition.{key}")

    # --- Per-element fold changes, both scales ---------------------------
    for row in comparison.itertuples():
        crop = CROP_KEYS[row.group]
        element = ELEMENT_KEYS.get(row.element, row.element)
        m.add(macro_name("FC", crop, element), row.fold_change_conc,
              f"plant_contrasts_comparison.csv:{row.group}/{row.element} concentration",
              fmt="{:.2f}")
        m.add(macro_name("FCCLR", crop, element), row.fold_change_clr,
              f"plant_contrasts_comparison.csv:{row.group}/{row.element} CLR",
              fmt="{:.2f}")
        m.add(macro_name("Q", crop, element), row.p_adjusted_bh_conc,
              f"plant_contrasts_comparison.csv:{row.group}/{row.element} q concentration",
              fmt="{:.3f}")
        m.add(macro_name("QCLR", crop, element), row.p_adjusted_bh_clr,
              f"plant_contrasts_comparison.csv:{row.group}/{row.element} q CLR",
              fmt="{:.3f}")

    m.add("NSigConc", plant["n_significant_concentration_fdr05"],
          "plant_summary.json:n_significant_concentration_fdr05")
    m.add("NSigCLR", plant["n_significant_clr_fdr05"],
          "plant_summary.json:n_significant_clr_fdr05")
    m.add("NSigBoth", plant["n_significant_both"], "plant_summary.json:n_significant_both")
    m.add("NDivergentCLR", plant.get("n_divergent_elements_clr"),
          "plant_summary.json:n_divergent_elements_clr")
    m.add("DivergentElementsCLR",
          ", ".join(ELEMENT_KEYS.get(e, e) for e in plant.get("divergent_elements_clr", [])),
          "plant_summary.json:divergent_elements_clr")

    # --- Machine learning -------------------------------------------------
    for scheme_name, scheme in ml["schemes"].items():
        tag = "Mission" if "Mission" in scheme_name else "Crop"
        m.add(macro_name("MLFolds", tag), scheme["n_folds"],
              f"ml_results.json:{scheme_name}.n_folds")
        m.add(macro_name("MLBaseline", tag), scheme["best_baseline_balanced_accuracy"],
              f"ml_results.json:{scheme_name}.best_baseline", fmt="{:.3f}")
        for model_name, entry in scheme["models"].items():
            if entry["is_baseline"]:
                continue
            short = "RF" if "forest" in model_name else "LR"
            m.add(macro_name("ML", tag, short), entry["balanced_accuracy"],
                  f"ml_results.json:{scheme_name}.{model_name}.balanced_accuracy",
                  fmt="{:.3f}")
            m.add(macro_name("ML", tag, short, "Margin"), entry["margin_over_baseline"],
                  f"ml_results.json:{scheme_name}.{model_name}.margin_over_baseline",
                  fmt="{:+.3f}")
            low, high = entry["accuracy_ci95"]
            m.add(macro_name("ML", tag, short, "CI"), f"{low:.2f}--{high:.2f}",
                  f"ml_results.json:{scheme_name}.{model_name}.accuracy_ci95")
    m.add("MLNFeatures", len(ml["features_used"]), "ml_results.json:features_used")
    m.add("MLFeatures",
          ", ".join(ELEMENT_KEYS.get(f, f) for f in ml["features_used"]),
          "ml_results.json:features_used")
    for i, row in enumerate(ml["permutation_importance_top5"][:3], start=1):
        m.add(macro_name("MLTop", ["One", "Two", "Three"][i - 1]),
              ELEMENT_KEYS.get(row["feature"], row["feature"]),
              f"ml_results.json:permutation_importance_top5[{i-1}]")

    # --- LSDA catalog -----------------------------------------------------
    m.add("LSDATotal", lsda["n_experiments_total"], "lsda_catalog_summary.json")
    m.add("LSDARelevant", lsda["n_mineral_or_nutrition"], "lsda_catalog_summary.json")
    m.add("LSDAMeasured", lsda["n_measured_mineral_or_nutrition"], "lsda_catalog_summary.json")
    m.add("LSDAHuman", lsda["n_human_studies"], "lsda_catalog_summary.json")
    for category, count in lsda["measured_by_access_category"].items():
        m.add(macro_name("LSDAAccess", category), count,
              f"lsda_catalog_summary.json:measured_by_access_category.{category}")
    for element, count in lsda["by_mineral_measured"].items():
        m.add(macro_name("LSDAMeas", ELEMENT_KEYS.get(element, element)), count,
              f"lsda_catalog_summary.json:by_mineral_measured.{element}")

    # --- Astronaut --------------------------------------------------------
    m.add("AstroN", astro["n_subjects"], "astronaut_summary.json:n_subjects")
    m.add("AstroTimepoints", astro["n_timepoints"], "astronaut_summary.json:n_timepoints")
    m.add("AstroObs", astro["n_observations"], "astronaut_summary.json:n_observations")
    m.add("AstroDuration", astro["mission_duration_days"],
          "astronaut_summary.json:mission_duration_days")
    for mineral, entry in astro["by_mineral"].items():
        tag = ELEMENT_KEYS.get(mineral, mineral.replace("_", ""))
        m.add(macro_name("AstroDown", tag), entry["n_decreased_at_return"],
              f"astronaut_summary.json:by_mineral.{mineral}.n_decreased_at_return")
        m.add(macro_name("AstroPct", tag), entry["median_percent_change"],
              f"astronaut_summary.json:by_mineral.{mineral}.median_percent_change",
              fmt="{:.1f}")

    # --- Supply / bioavailability proxy -----------------------------------
    m.add("SupplyMatched", supply["n_with_supplement"], "supply_summary.json")
    m.add("SupplyTotal", supply["n_tokyo_bekana_samples"], "supply_summary.json")
    for condition, entry in supply["by_condition"].items():
        if "mean_total_water_ml" in entry:
            m.add(macro_name("Water", condition), entry["mean_total_water_ml"],
                  f"supply_summary.json:by_condition.{condition}.mean_total_water_ml",
                  fmt="{:.0f}")
            m.add(macro_name("Biomass", condition), entry["mean_harvested_fresh_g"],
                  f"supply_summary.json:by_condition.{condition}.mean_harvested_fresh_g",
                  fmt="{:.1f}")
            if entry.get("mean_water_use_efficiency_g_per_l"):
                m.add(macro_name("WUE", condition),
                      entry["mean_water_use_efficiency_g_per_l"],
                      f"supply_summary.json:by_condition.{condition}.wue", fmt="{:.1f}")

    # --- Serving contribution and overload --------------------------------
    for key, value in integration["percent_of_requirement_per_100g"].items():
        crop, condition, element = key.split("/")
        if condition != "Flight":
            continue
        m.add(macro_name("Serve", CROP_KEYS[crop], ELEMENT_KEYS.get(element, element)),
              value, f"integration_summary.json:{key}", fmt="{:.1f}")
    for row in overload[
        (overload.condition == "Flight") & (overload.dry_matter_assumption == "high")
    ].itertuples():
        m.add(macro_name("Overload", ELEMENT_KEYS.get(row.element, row.element),
                         CROP_KEYS[row.crop]),
              row.kilograms_fresh_to_reach_upper_limit,
              f"overload_assessment.csv:{row.element}/{row.crop}", fmt="{:.2f}")

    # --- QC ---------------------------------------------------------------
    m.add("QCAllPassed", "yes" if qc["all_passed"] else "NO",
          "qc_report.json:all_passed")
    m.add("NUnitOverrides",
          len(pd.read_csv(PROCESSED / "unit_provenance.csv").query("override_applied")),
          "unit_provenance.csv:override_applied")

    output = MANUSCRIPT / "generated_numbers.tex"
    output.write_text(m.render())
    log.info("wrote %s with %d macros", output, len(m.entries))


if __name__ == "__main__":
    main()
